export function t(language: Language, key: string): string {
  if (language === "en") return key;
  const translated = fa[key];
  if (translated) return translated;
  if (import.meta.env.DEV) console.warn(`Missing Persian translation key: ${key}`);
  return "ترجمه در دسترس نیست";
}

export function formatUnit(value: string, language: Language): string {
  if (language === "en") return value;
  return fa[value] ?? value;
}

export function localizeError(language: Language, message: string): string {
  if (language === "en") return message;
  return fa[message] ?? fa["Request failed."];
}

export function formatNumber(value: number, language: Language): string {
  return new Intl.NumberFormat(language === "fa" ? "fa-IR" : "en-US").format(value);
}

export function formatDate(value: string | Date, language: Language): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(language === "fa" ? "fa-IR-u-ca-persian" : "en-US").format(date);
}

export function formatCurrency(value: number, language: Language, currency = "USD"): string {
  return new Intl.NumberFormat(language === "fa" ? "fa-IR" : "en-US", {
    style: "currency",
    currency,
    maximumFractionDigits: 2,
  }).format(value);
}

export function normalizeLocalizedNumber(value: string): string {
  const digits = "۰۱۲۳۴۵۶۷۸۹";
  const arabicDigits = "٠١٢٣٤٥٦٧٨٩";
  return value
    .replace(/[۰-۹]/g, (digit) => String(digits.indexOf(digit)))
    .replace(/[٠-٩]/g, (digit) => String(arabicDigits.indexOf(digit)))
    .replace(/[٬,،]/g, "")
    .replace(/٫/g, ".")
    .trim();
}
